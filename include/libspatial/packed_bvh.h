/* Packed N-dimensional point BVH. MIT. Independent of legacy spatial_bvh. */
#ifndef LIBSPATIAL_PACKED_BVH_H
#define LIBSPATIAL_PACKED_BVH_H
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include <limits.h>
typedef struct spatial_packed_bvh_node { uint32_t first,second; uint8_t leaf,reserved[3]; } spatial_packed_bvh_node;
typedef struct spatial_packed_bvh {
 uint32_t dims,count,leaf_size,node_count;
 uint32_t *order;
 spatial_packed_bvh_node *nodes;
 float *lo,*hi;
 const float *points;
} spatial_packed_bvh;
typedef struct spatial_packed_bvh_hit {uint32_t id; double distance2;} spatial_packed_bvh_hit;
typedef struct spatial_packed_bvh_queue {uint32_t node;double lower_bound;} spatial_packed_bvh_queue;
typedef struct spatial_packed_bvh_scratch {spatial_packed_bvh_queue *queue;size_t queue_capacity;} spatial_packed_bvh_scratch;
static inline void spatial_packed_bvh_destroy(spatial_packed_bvh *b){
 if(!b)return;free(b->order);free(b->nodes);free(b->lo);free(b->hi);memset(b,0,sizeof(*b));
}
typedef struct spatial_packed_sort_entry {uint64_t key;uint32_t id;} spatial_packed_sort_entry;
static int spatial_packed_sort_cmp(const void *a,const void *b){
 const spatial_packed_sort_entry *x=(const spatial_packed_sort_entry*)a,*y=(const spatial_packed_sort_entry*)b;
 if(x->key!=y->key)return x->key<y->key?-1:1;return (x->id>y->id)-(x->id<y->id);
}
static inline uint32_t spatial_packed_build_node(spatial_packed_bvh *b,uint32_t first,uint32_t count){
 uint32_t n=b->node_count++;spatial_packed_bvh_node *p=&b->nodes[n];
 if(count<=b->leaf_size){
  p->leaf=1;p->first=first;p->second=count;
  for(uint32_t d=0;d<b->dims;++d){
   float mn=INFINITY,mx=-INFINITY;
   for(uint32_t i=first;i<first+count;++i){
    float v=b->points[(size_t)b->order[i]*b->dims+d];
    if(v<mn)mn=v;if(v>mx)mx=v;
   }
   b->lo[(size_t)n*b->dims+d]=mn;b->hi[(size_t)n*b->dims+d]=mx;
  }
 }else{
  uint32_t lc=count/2,l=spatial_packed_build_node(b,first,lc),r=spatial_packed_build_node(b,first+lc,count-lc);
  p->leaf=0;p->first=l;p->second=r;
  for(uint32_t d=0;d<b->dims;++d){
   float a=b->lo[(size_t)l*b->dims+d],c=b->lo[(size_t)r*b->dims+d];
   float x=b->hi[(size_t)l*b->dims+d],y=b->hi[(size_t)r*b->dims+d];
   b->lo[(size_t)n*b->dims+d]=a<c?a:c;b->hi[(size_t)n*b->dims+d]=x>y?x:y;
  }
 }return n;
}
/* Optional uint64 Hilbert/Morton keys are generated by caller, e.g. curves.h.
 * Original float vectors always determine exact node bounds and distances.
 * Build into an initially empty out; destroy before rebuilding. */
static inline int spatial_packed_bvh_build(spatial_packed_bvh *out,const float *points,
 const uint64_t *keys,uint32_t count,uint32_t dims,uint32_t leaf_size){
 if(!out||!points||!count||!dims||dims>256||!leaf_size||count>UINT32_MAX/2||
 (size_t)count>SIZE_MAX/(size_t)dims||
 (size_t)(2u*count)>SIZE_MAX/(size_t)dims||
 (size_t)(2u*count)*(size_t)dims>SIZE_MAX/sizeof(float))return -1;
 spatial_packed_bvh b={0};b.count=count;b.dims=dims;b.leaf_size=leaf_size;b.points=points;
 b.order=(uint32_t*)malloc((size_t)count*sizeof(uint32_t));
 b.nodes=(spatial_packed_bvh_node*)calloc((size_t)2*count,sizeof(*b.nodes));
 b.lo=(float*)malloc((size_t)2*count*dims*sizeof(float));
 b.hi=(float*)malloc((size_t)2*count*dims*sizeof(float));
 if(!b.order||!b.nodes||!b.lo||!b.hi)goto fail;
 if(keys){
  spatial_packed_sort_entry *s=(spatial_packed_sort_entry*)malloc((size_t)count*sizeof(*s));
  if(!s)goto fail;
  for(uint32_t i=0;i<count;++i){s[i].key=keys[i];s[i].id=i;}
  qsort(s,count,sizeof(*s),spatial_packed_sort_cmp);
  for(uint32_t i=0;i<count;++i)b.order[i]=s[i].id;
  free(s);
 }else for(uint32_t i=0;i<count;++i)b.order[i]=i;
 for(size_t i=0;i<(size_t)count*dims;++i)if(!isfinite(points[i]))goto fail;
 spatial_packed_build_node(&b,0,count);*out=b;return 0;
 fail:spatial_packed_bvh_destroy(&b);return -1;
}
static inline double spatial_packed_bound2(const spatial_packed_bvh *b,uint32_t node,const float *q){
 double sum=0;size_t off=(size_t)node*b->dims;
 for(uint32_t d=0;d<b->dims;++d){
  double v=q[d],delta=0;
  if(v<b->lo[off+d])delta=(double)b->lo[off+d]-v;
  else if(v>b->hi[off+d])delta=v-(double)b->hi[off+d];
  sum+=delta*delta;
 }return sum;
}
static inline double spatial_packed_dist2(const float *a,const float *b,uint32_t dims){
 double s=0;for(uint32_t d=0;d<dims;++d){double x=(double)a[d]-b[d];s+=x*x;}return s;
}
static inline int spatial_packed_hit_better(spatial_packed_bvh_hit a,spatial_packed_bvh_hit b){
 return a.distance2<b.distance2||((!(a.distance2<b.distance2)&&!(b.distance2<a.distance2))&&a.id<b.id);
}
static inline int spatial_packed_q_less(spatial_packed_bvh_queue a,spatial_packed_bvh_queue b){
 return a.lower_bound<b.lower_bound||((!(a.lower_bound<b.lower_bound)&&!(b.lower_bound<a.lower_bound))&&a.node<b.node);
}
static inline void spatial_packed_q_push(spatial_packed_bvh_queue *q,size_t *n,spatial_packed_bvh_queue x){
 size_t i=(*n)++;while(i){size_t p=(i-1)/2;if(!spatial_packed_q_less(x,q[p]))break;q[i]=q[p];i=p;}q[i]=x;
}
static inline spatial_packed_bvh_queue spatial_packed_q_pop(spatial_packed_bvh_queue *q,size_t *n){
 spatial_packed_bvh_queue r=q[0],x=q[--*n];if(!*n)return r;size_t i=0;
 while(2*i+1<*n){size_t c=2*i+1;if(c+1<*n&&spatial_packed_q_less(q[c+1],q[c]))++c;
 if(!spatial_packed_q_less(q[c],x))break;q[i]=q[c];i=c;}q[i]=x;return r;
}
/* Exact ascending squared L2, deterministic ID tie-break, no query allocation.
 * Scratch queue capacity >= node_count. Returns SIZE_MAX on invalid args. */
static inline size_t spatial_packed_bvh_knn(const spatial_packed_bvh *b,const float *query,
 size_t k,spatial_packed_bvh_hit *out,spatial_packed_bvh_scratch scratch){
 if(!b||!b->nodes||!query||(k&&!out)||!scratch.queue||scratch.queue_capacity<b->node_count)return SIZE_MAX;
 for(uint32_t d=0;d<b->dims;++d)if(!isfinite(query[d]))return SIZE_MAX;
 if(!k)return 0;if(k>b->count)k=b->count;size_t used=0,qn=0;
 spatial_packed_q_push(scratch.queue,&qn,(spatial_packed_bvh_queue){0,spatial_packed_bound2(b,0,query)});
 while(qn){
  spatial_packed_bvh_queue item=spatial_packed_q_pop(scratch.queue,&qn);
  if(used==k&&item.lower_bound>out[used-1].distance2)break;
  const spatial_packed_bvh_node *n=&b->nodes[item.node];
  if(n->leaf){
   for(uint32_t i=n->first;i<n->first+n->second;++i){
    uint32_t id=b->order[i];spatial_packed_bvh_hit h={id,spatial_packed_dist2(query,b->points+(size_t)id*b->dims,b->dims)};
    size_t pos=0;while(pos<used&&!spatial_packed_hit_better(h,out[pos]))++pos;
    if(pos>=k)continue;if(used<k)++used;
    for(size_t j=used-1;j>pos;--j)out[j]=out[j-1];out[pos]=h;
   }
  }else{
   uint32_t children[2]={n->first,n->second};
   for(int c=0;c<2;++c){
    double bound=spatial_packed_bound2(b,children[c],query);
    if(used<k||bound<=out[used-1].distance2)
     spatial_packed_q_push(scratch.queue,&qn,(spatial_packed_bvh_queue){children[c],bound});
   }
  }
 }return used;
}
#endif
